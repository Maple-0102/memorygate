"""Second-model replication of the week-1 retrieval check (exploratory; see reports/model2_plan.md).

For each model, on the validation questions gradable in both runs of a pair:
  - accuracy of each run, the difference in percentage points, a normal-approximation 95% interval
    from the per-question differences, the two-sided p value, and fixed/broken counts.
Usage: python -m memorygate.model2_stats [out_path]
"""
from __future__ import annotations

import sys
from math import erfc, sqrt
from pathlib import Path

from .runner import load_traj

RUNS = Path("runs")
MODELS = {
    "gemini-3.5-flash-lite (week 1)": {"none": "nomem_r1", "relevant": "raw_k3", "random": "shuf_k3"},
    "gemini-3.8-flash": {"none": "m2_nomem", "relevant": "m2_raw_k3", "random": "m2_shuf_k3"},
}
PAIRS = (("relevant", "none", "Relevant retrieval vs. no memory (primary)"),
         ("relevant", "random", "Relevant vs. random same-db past questions"),
         ("random", "none", "Random same-db past questions vs. no memory"))


def _graded(run: str) -> dict[str, bool]:
    return {r["qid"]: r["correct"] for r in load_traj(RUNS / run) if not r["gold_error"]}


def compare(a: dict[str, bool], b: dict[str, bool]) -> dict:
    """Run a minus run b on their shared items."""
    shared = sorted(a.keys() & b.keys())
    n = len(shared)
    d = [int(a[q]) - int(b[q]) for q in shared]
    mean = sum(d) / n
    var = sum((x - mean) ** 2 for x in d) / (n - 1)
    se = sqrt(var / n)
    z = mean / se if se else 0.0
    return {"n": n, "acc_a": sum(a[q] for q in shared) / n, "acc_b": sum(b[q] for q in shared) / n,
            "diff": mean, "lo": mean - 1.96 * se, "hi": mean + 1.96 * se, "z": z, "p": erfc(abs(z) / sqrt(2)),
            "fixed": sum(x == 1 for x in d), "broken": sum(x == -1 for x in d)}


def report() -> str:
    out = ["# Second-model replication of the week-1 retrieval check\n",
           "Generated by `python -m memorygate.model2_stats`. Exploratory, development data only (validation split); "
           "plan in `model2_plan.md`, written before the runs. k = 3 past questions per question, bank = learn split "
           "with the model's own earlier attempts. Every comparison for a model uses the questions gradable in all "
           "three of its runs.\n"]
    for model, runs in MODELS.items():
        if not all((RUNS / r).exists() for r in runs.values()):
            out.append(f"## {model}\n\nRuns missing.\n")
            continue
        g = {k: _graded(v) for k, v in runs.items()}
        common = set.intersection(*(set(x) for x in g.values()))  # one denominator for every comparison
        g = {k: {q: x[q] for q in common} for k, x in g.items()}
        out.append(f"## {model}\n")
        out.append("| Comparison | n | Accuracy A | Accuracy B | Δ (pp) | 95% CI | p | fixed / broken |")
        out.append("|---|---|---|---|---|---|---|---|")
        for a, b, label in PAIRS:
            c = compare(g[a], g[b])
            p = "<0.001" if c["p"] < 0.001 else f"{c['p']:.3f}"
            out.append(f"| {label} | {c['n']} | {c['acc_a']:.1%} | {c['acc_b']:.1%} | {100 * c['diff']:+.1f} | "
                       f"{100 * c['lo']:+.1f} to {100 * c['hi']:+.1f} | {p} | {c['fixed']} / {c['broken']} |")
        out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    text = report()
    path = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("reports/model2.md")
    path.write_text(text + "\n")
    print(text)
